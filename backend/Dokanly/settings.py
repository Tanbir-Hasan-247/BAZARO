def _bool_config(name: str, default: bool) -> bool:
    raw = config(name, default=None)
    if raw is None or str(raw).strip() == '':
        return default
    val = str(raw).strip().lower()
    if val in ('1', 'true', 'yes', 'on'):
        return True
    if val in ('0', 'false', 'no', 'off'):
        return False
    return default


